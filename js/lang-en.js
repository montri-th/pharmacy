/**
 * Pharmacy · English words (citymeter-shell, js/shell/i18n.js), keyed by the Thai the page shows. A draft translation
 * from the Thai source, not yet reviewed (demo-platform-review §5.8); the page says so. Pharmacy names, chain names and
 * place names are not here: js/lang.js registers the English the data carries (provinces and subdistricts from
 * production base info, districts from OpenGISData-Thailand, groups from groups[].en; chains are written in English by
 * the data); a pharmacy's name stays as its source writes it.
 * Terms: ร้าน = pharmacies (the default unit: one KhY1 licence of the FDA register = one premises); รายการ = records (one
 * dataset row; the same storefront can repeat); ขย1 = KhY1 (the FDA licence to sell modern medicines); อย. = FDA (Thai
 * Food and Drug Administration); สภาเภสัชกรรม = Pharmacy Council; ร้านยาคุณภาพ = quality pharmacy (on the Pharmacy
 * Council's Quality Pharmacy list); เครือร้าน = chain; ประเภทร้าน = pharmacy type; ชีตวิจัย = research sheet; แขวง/ตำบล
 * = subdistrict; เขต/อำเภอ = district; ตร.กม. = km².
 */
const N = '([\\d,]+)';
const D = '([\\d,.<]+)';
const U = '(ร้าน|รายการ)';
const W = '(แขวง|ตำบล|พื้นที่)';
/** A Thai date as the page writes it (js/panel.js#thaiDate): "28 พ.ค. 2569". */
const DT = '(\\d{1,2} [ก-๙.]+ \\d{4})';
const re = source => new RegExp(`^${source}$`);
const plural = (t, n, one, many) => `${n} ${t.plural(n, one, many)}`;
/** "N ร้าน" / "N รายการ" → "N pharmacies" / "N records". */
const units = (t, n, u) => (u === 'รายการ' ? plural(t, n, 'record', 'records') : plural(t, n, 'pharmacy', 'pharmacies'));
const unitWord = u => (u === 'รายการ' ? 'records' : 'pharmacies');
/** "3 แขวง" / "3 พื้นที่" → "3 subdistricts" / "3 areas". */
const areas = (t, n, w) => (w === 'พื้นที่' ? plural(t, n, 'area', 'areas') : plural(t, n, 'subdistrict', 'subdistricts'));
/** "3 แขวงนี้" → "these 3 subdistricts" / "this subdistrict". */
const these = (n, w) => {
  const one = w === 'พื้นที่' ? 'area' : 'subdistrict';
  return n === '1' ? `this ${one}` : `these ${n} ${one}s`;
};
/** Place words written one after another ("แขวงดินแดง เขตดินแดง กรุงเทพมหานคร") → "Din Daeng, Din Daeng, Bangkok"; the
 * longest known run first, so a name with a space ("ปอภาร (ปอพาน)") stays one name. */
function places(t, text) {
  const words = text.replace(/ · /g, ' ').split(' ').filter(Boolean);
  const out = [];
  for (let i = 0; i < words.length;) {
    let j = words.length;
    while (j > i + 1 && !t.known(words.slice(i, j).join(' '))) j--;
    const run = words.slice(i, j).join(' ');
    out.push(t.known(run) ?? t.name(run));
    i = j;
  }
  return out.join(', ');
}
